"""Generate the CLI and configuration reference pages under docs/reference.

Run `uv run python scripts/gen_reference.py` after changing a CLI option, a
config model or a handler config. `--check` exits non-zero when the committed
pages are out of date.
"""

import argparse
import enum
import inspect
import os
import sys
import types
import typing
from pathlib import Path

import click
from pydantic import BaseModel
from pydantic_core import PydanticUndefined

import tfworker.handlers  # noqa: F401
from tfworker import constants as const
from tfworker.cli import cli
from tfworker.custom_types.config_file import (
    ConfigFile,
    DefinitionsSource,
    GlobalVars,
    LockingOptions,
    ParallelOptions,
)
from tfworker.definitions.model import Definition, DefinitionRemoteOptions
from tfworker.handlers.registry import HandlerRegistry
from tfworker.providers.model import ProviderAlias, ProviderConfig, ProviderRequirements

REPO_ROOT = Path(__file__).resolve().parent.parent
REFERENCE_DIR = REPO_ROOT / "docs" / "reference"
HEADER = (
    "<!-- Generated by scripts/gen_reference.py. Do not edit by hand; "
    "run `make docs` instead. -->\n\n"
)

# Fields the worker sets while it runs; they are not configuration.
INTERNAL_DEFINITION_FIELDS = {
    "name",
    "ready",
    "needs_apply",
    "plan_failed",
    "init_failed",
    "init_skipped",
    "apply_failed",
    "apply_skipped",
    "plan_file",
}


def _escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _portable(value: str) -> str:
    """Replace the generating machine's working directory with `.`."""
    return value.replace(const.DEFAULT_REPOSITORY_PATH, ".")


# --- CLI reference -----------------------------------------------------------


def _option_default(param: click.Option) -> str:
    default = param.default
    if callable(default) or default is None:
        return ""
    if param.is_flag and param.secondary_opts:
        flag = param.opts[0] if default else param.secondary_opts[0]
        return f"`{flag}`"
    if isinstance(default, (list, tuple)):
        if not default:
            return ""
        return ", ".join(f"`{_portable(str(d))}`" for d in default)
    if isinstance(default, enum.Enum):
        default = default.value
    return f"`{_portable(str(default))}`"


def _option_name(param: click.Option) -> str:
    names = " / ".join(f"`{opt}`" for opt in param.opts + param.secondary_opts)
    if param.multiple:
        names += " (repeatable)"
    return names


def _command_section(name: str, command: click.Command, level: int) -> list[str]:
    lines = [f"{'#' * level} {name}", ""]
    help_text = inspect.cleandoc(command.help or "")
    if help_text:
        lines += [help_text, ""]

    usage_parts = [name]
    if isinstance(command, click.Group):
        usage_parts += ["[OPTIONS]", "COMMAND [ARGS]..."]
    else:
        usage_parts.append("[OPTIONS]")
        for param in command.params:
            if isinstance(param, click.Argument):
                usage_parts.append(param.human_readable_name)
    lines += ["```", " ".join(usage_parts), "```", ""]

    arguments = [p for p in command.params if isinstance(p, click.Argument)]
    for argument in arguments:
        env = f" Can also be set with `{argument.envvar}`." if argument.envvar else ""
        lines += [f"`{argument.human_readable_name}` is required.{env}", ""]

    options = sorted(
        (
            p
            for p in command.params
            if isinstance(p, click.Option) and p.expose_value and not p.hidden
        ),
        key=lambda p: p.opts[0],
    )
    if options:
        lines += [
            "| Option | Environment variable | Default | Description |",
            "| --- | --- | --- | --- |",
        ]
        for option in options:
            env = f"`{option.envvar}`" if option.envvar else ""
            lines.append(
                f"| {_option_name(option)} | {env} | {_option_default(option)} "
                f"| {_escape(option.help or '')} |"
            )
        lines.append("")
    return lines


def render_cli() -> str:
    lines = [
        "# CLI reference",
        "",
        "Every option can also be set with its environment variable, and most root",
        "options with `worker_options` in the configuration file. See",
        "[Running the worker](../running.md) for how the commands fit together.",
        "",
    ]
    lines += _command_section("worker", cli, 2)
    for name in sorted(cli.commands):
        lines += _command_section(f"worker {name}", cli.commands[name], 2)
    return HEADER + "\n".join(lines).rstrip() + "\n"


# --- Configuration reference -------------------------------------------------


def _type_name(annotation) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin in (typing.Union, types.UnionType):
        names = [_type_name(a) for a in args if a is not type(None)]
        return " or ".join(dict.fromkeys(names))
    if origin in (list, typing.List):
        return f"list of {_type_name(args[0])}" if args else "list"
    if origin in (dict, typing.Dict):
        return f"map of {_type_name(args[1])}" if args else "map"
    if annotation is typing.Any:
        return "any"
    if isinstance(annotation, type):
        if issubclass(annotation, enum.Enum):
            return " \\| ".join(f"`{m.value}`" for m in annotation)
        if issubclass(annotation, BaseModel):
            return "object"
        return {
            str: "string",
            int: "integer",
            float: "number",
            bool: "boolean",
            dict: "map",
            list: "list",
        }.get(annotation, annotation.__name__)
    return str(annotation)


def _field_default(field) -> str:
    if field.is_required():
        return "required"
    if field.default_factory is not None:
        value = field.default_factory()
    else:
        value = field.default
    if value is None or value is PydanticUndefined:
        return ""
    if isinstance(value, BaseModel):
        return ""
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, list):
        value = [v.value if isinstance(v, enum.Enum) else v for v in value]
        if not value:
            return ""
        return "`[" + ", ".join(str(v) for v in value) + "]`"
    if isinstance(value, dict) and not value:
        return ""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if not isinstance(value, (str, int, float)):
        return "built in"
    text = str(value)
    if "\n" in text or len(text) > 40:
        return "built in"
    return f"`{text}`"


def _model_table(model: type[BaseModel], skip: set[str] = frozenset()) -> list[str]:
    lines = [
        "| Field | Type | Default | Description |",
        "| --- | --- | --- | --- |",
    ]
    for name, field in model.model_fields.items():
        if name in skip:
            continue
        lines.append(
            f"| `{name}` | {_type_name(field.annotation)} | {_field_default(field)} "
            f"| {_escape(field.description or '')} |"
        )
    return lines + [""]


def _model_section(
    title: str, model: type[BaseModel], intro: str, skip: set[str] = frozenset()
) -> list[str]:
    return [f"### {title}", "", intro, ""] + _model_table(model, skip)


def render_config() -> str:
    lines = [
        "# Configuration reference",
        "",
        "The configuration file is YAML, JSON or HCL with everything under a",
        "top-level `terraform` key. It is rendered with Jinja before it is",
        "parsed; see [Configuration](../configuration.md) for how the pieces",
        "fit together.",
        "",
        "## Top level",
        "",
        "Keys allowed under `terraform`.",
        "",
    ]
    lines += _model_table(ConfigFile)
    lines += ["## Sections", ""]
    lines += _model_section(
        "definitions.&lt;name&gt;",
        Definition,
        "Each entry under `definitions` is one terraform root module run as its own state.",
        INTERNAL_DEFINITION_FIELDS,
    )
    lines += _model_section(
        "definitions.&lt;name&gt;.remote_path_options",
        DefinitionRemoteOptions,
        "Options for a definition or definitions source whose `path` is a git URL.",
    )
    lines += _model_section(
        "definitions_sources.&lt;name&gt;",
        DefinitionsSource,
        "A source whose command prints more definitions when the configuration loads.",
    )
    lines += _model_section(
        "global_vars",
        GlobalVars,
        "Variables merged into every definition unless the definition opts out.",
    )
    lines += _model_section(
        "providers.&lt;name&gt;",
        ProviderConfig,
        "One entry per terraform provider used by the definitions.",
    )
    lines += _model_section(
        "providers.&lt;name&gt;.requirements",
        ProviderRequirements,
        "Rendered into each definition's `required_providers` block.",
    )
    lines += _model_section(
        "providers.&lt;name&gt;.aliases.&lt;alias&gt;",
        ProviderAlias,
        "An aliased provider block; its values override the provider's own.",
    )
    lines += _model_section(
        "parallel_options",
        ParallelOptions,
        "How many definitions are prepared and initialized at once.",
    )
    lines += _model_section(
        "locking",
        LockingOptions,
        "Waits for held state locks; off when the block is absent. Durations are "
        "seconds or strings such as `90s` and `1h30m`, and `actions` takes `plan`, "
        "`apply` and `destroy`. See [State locks](../locking.md).",
    )
    lines += [
        "## Handlers",
        "",
        "Each key under `handlers` turns on the handler of that name with the",
        "options below. Handlers marked always-on run without a `handlers` entry.",
        "",
    ]
    universal = set(HandlerRegistry.list_universal_handlers())
    for name in sorted(HandlerRegistry.get_handler_names()):
        model = HandlerRegistry.get_handler_config_model(name)
        handler = HandlerRegistry.get_handler(name)
        summary = inspect.cleandoc(handler.__doc__ or model.__doc__ or "").split(
            "\n\n"
        )[0]
        lines += [f"### handlers.{name}", ""]
        if name in universal:
            lines += ["Always on.", ""]
        if summary:
            lines += [_escape(summary), ""]
        if model.model_fields:
            lines += _model_table(model)
        else:
            lines += ["No options.", ""]
    return HEADER + "\n".join(lines).rstrip() + "\n"


PAGES = {
    "cli.md": render_cli,
    "config.md": render_config,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed pages differ from the generated ones",
    )
    args = parser.parse_args(argv)

    stale = []
    for filename, render in PAGES.items():
        path = REFERENCE_DIR / filename
        content = render()
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(os.path.relpath(path, REPO_ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {os.path.relpath(path, REPO_ROOT)}")

    if stale:
        print(
            "out of date: "
            + ", ".join(stale)
            + "; run `make docs` and commit the result",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
